-- Week 5: user-owned meme posts and the daily prompt.
-- Images live in Supabase Storage; relational rows hold only the public URL
-- and accessible supporting text.

begin;

create table if not exists public.daily_detours (
  id bigint generated by default as identity primary key,
  title text not null,
  prompt text not null,
  active_on date not null default current_date unique,
  created_at timestamptz not null default now()
);

alter table public.daily_detours enable row level security;

drop policy if exists "Anyone can read daily detours" on public.daily_detours;
create policy "Anyone can read daily detours"
on public.daily_detours
for select
to anon, authenticated
using (true);

insert into public.daily_detours (title, prompt)
values (
  'The elevator has a bit',
  'The campus elevator makes one sound that tells you it has given up.'
)
on conflict (active_on) do nothing;

alter table public.captions
  add column if not exists challenge_id bigint references public.daily_detours(id) on delete set null,
  add column if not exists media_alt text;

alter table public.captions
  drop constraint if exists captions_media_key_check;

alter table public.captions
  add constraint captions_media_key_check
  check (media_key in ('uptown-platform', 'dorm-desk', 'soho-coffee', 'city-after-class', 'user-upload'));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'caption-media',
  'caption-media',
  true,
  4194304,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can view caption media" on storage.objects;
drop policy if exists "Users can upload their own caption media" on storage.objects;
drop policy if exists "Users can update their own caption media" on storage.objects;
drop policy if exists "Users can remove their own caption media" on storage.objects;

create policy "Anyone can view caption media"
on storage.objects
for select
to anon, authenticated
using (bucket_id = 'caption-media');

create policy "Users can upload their own caption media"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'caption-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "Users can update their own caption media"
on storage.objects
for update
to authenticated
using (
  bucket_id = 'caption-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
)
with check (
  bucket_id = 'caption-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

create policy "Users can remove their own caption media"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'caption-media'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

commit;
